import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Builds the MCP App checkout card into one HTML file and embeds it as a JS
 * string, so the serverless function never needs a filesystem read at runtime.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
execFileSync('npx', ['vite', 'build', '--config', 'mcp-app/vite.config.js'], {
  cwd: root,
  stdio: 'inherit',
});

const html = readFileSync(resolve(root, 'mcp-app-dist/index.html'), 'utf8');
const out = `// Generated by scripts/build-mcp-app.mjs. Do not edit by hand.\nexport const checkoutHtml = ${JSON.stringify(html)};\n`;
mkdirSync(resolve(root, 'mcp/apps'), { recursive: true });
writeFileSync(resolve(root, 'mcp/apps/checkoutHtml.generated.js'), out);
console.log(`[mcp-app] embedded ${html.length} bytes into mcp/apps/checkoutHtml.generated.js`);
